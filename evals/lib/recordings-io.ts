import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { Recording } from '../../lib/ai/types';

export const RECORDINGS_DIR = path.resolve(process.cwd(), 'evals', 'recordings');

function fileNameFor(rec: Recording): string {
  const agent = rec.agent.replace(/[^a-zA-Z0-9.-]/g, '_');
  const label = rec.label ? `__${rec.label.replace(/[^a-zA-Z0-9-]/g, '_')}` : '';
  return `${agent}${label}__${rec.key.slice(0, 16)}.json`;
}

/** Replaces every recording with `recordings` and regenerates the static index used by lib/ai/replay.ts. */
export function writeRecordings(recordings: Recording[]): string[] {
  mkdirSync(RECORDINGS_DIR, { recursive: true });
  for (const f of readdirSync(RECORDINGS_DIR)) {
    if (f.endsWith('.json')) rmSync(path.join(RECORDINGS_DIR, f));
  }
  const unique = new Map(recordings.map((r) => [r.key, r]));
  const files: string[] = [];
  for (const rec of unique.values()) {
    const file = fileNameFor(rec);
    writeFileSync(path.join(RECORDINGS_DIR, file), `${JSON.stringify(rec, null, 2)}\n`, 'utf8');
    files.push(file);
  }
  files.sort();
  const imports = files.map((f, i) => `import r${i} from './${f}';`).join('\n');
  const list = files.map((_, i) => `  r${i} as unknown as Recording,`).join('\n');
  const index = `// Generated by evals/lib/recordings-io.ts. Do not edit by hand.
import type { Recording } from '../../lib/ai/types';
${imports}

export const RECORDINGS: Recording[] = [
${list}
];
`;
  writeFileSync(path.join(RECORDINGS_DIR, 'index.ts'), index, 'utf8');
  return files;
}
